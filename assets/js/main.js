(() => {
  // Primary navigation: always visible on wide screens, toggled by the menu button on small ones
  const toggle = document.querySelector("[data-menu-toggle]");
  const nav = document.getElementById("primary-nav");
  if (toggle && nav) {
    const label = toggle.querySelector("[data-menu-label]");
    const setOpen = (open) => {
      nav.classList.toggle("is-open", open);
      toggle.setAttribute("aria-expanded", String(open));
      if (label) label.textContent = open ? label.dataset.close : label.dataset.open;
    };
    toggle.addEventListener("click", () => setOpen(!nav.classList.contains("is-open")));
    document.addEventListener("keydown", (e) => { if (e.key === "Escape" && nav.classList.contains("is-open")) { setOpen(false); toggle.focus(); } });
  }

  // Suggested programme: highlight the courses of one concentration
  const pf = document.querySelector("[data-programme-filter]");
  if (pf) {
    const buttons = [...pf.querySelectorAll("button")];
    const items = [...document.querySelectorAll(".semesters .course")];
    pf.addEventListener("click", (e) => {
      const b = e.target.closest("button"); if (!b) return;
      buttons.forEach((x) => x.setAttribute("aria-pressed", String(x === b)));
      const tag = b.dataset.tag;
      items.forEach((li) => {
        const t = li.dataset.tags.split(" ");
        li.classList.toggle("is-dim", !!tag && !t.includes(tag) && !t.includes("required"));
      });
    });
  }

  // Timetable: show one year (or graduate courses) only
  const tf = document.querySelector("[data-tt-filter]");
  if (tf) {
    const buttons = [...tf.querySelectorAll("button")];
    const rows = [...document.querySelectorAll("table.tt tbody tr")];
    tf.addEventListener("click", (e) => {
      const b = e.target.closest("button"); if (!b) return;
      buttons.forEach((x) => x.setAttribute("aria-pressed", String(x === b)));
      const y = b.dataset.year;
      rows.forEach((r) => { r.hidden = !!y && r.dataset.year !== y; });
    });
  }

  // Weekly timetable grids (hours x rooms per day): programme view + day tabs
  document.querySelectorAll("[data-ttg]").forEach((g) => {
    const days = ["Δευτέρα", "Τρίτη", "Τετάρτη", "Πέμπτη", "Παρασκευή"];
    const wd = new Date().getDay();                       // 0 = Sunday
    let day = days[wd >= 1 && wd <= 5 ? wd - 1 : 0];
    let view = g.dataset.view;
    const show = () => {
      g.querySelectorAll("[data-ttg-for]").forEach((t) => { t.hidden = t.dataset.ttgFor !== `${view}|${day}`; });
      g.querySelectorAll("[data-ttg-view]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.ttgView === view)));
      g.querySelectorAll("[data-ttg-day]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.ttgDay === day)));
    };
    g.addEventListener("click", (e) => {
      const b = e.target.closest("button"); if (!b) return;
      if (b.dataset.ttgView) view = b.dataset.ttgView;
      if (b.dataset.ttgDay) day = b.dataset.ttgDay;
      show();
    });
    g.classList.add("ttg--js");
    show();
  });

  // Obfuscated e-mail addresses
  document.querySelectorAll(".js-email").forEach((a) => {
    const addr = `${a.dataset.u}@${a.dataset.d}`;
    a.href = `mailto:${addr}`;
    a.textContent = addr;
  });

  // People directory filter
  const filter = document.querySelector("[data-people-filter]");
  if (filter) {
    const input = filter.querySelector("input");
    const select = filter.querySelector("select");
    const fold = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
    const cards = [...document.querySelectorAll(".person-card")];
    const groups = [...document.querySelectorAll("[data-people-group]")];
    const apply = () => {
      const q = fold(input.value.trim());
      const sector = select ? select.value : "";
      cards.forEach((c) => {
        const ok = (!q || fold(c.dataset.search).includes(q)) && (!sector || c.dataset.sector === sector);
        c.hidden = !ok;
      });
      groups.forEach((g) => { g.hidden = !g.querySelector(".person-card:not([hidden])"); });
    };
    input.addEventListener("input", apply);
    if (select) select.addEventListener("change", apply);
  }

  // Site search (search.json is generated by Jekyll)
  const results = document.querySelector("[data-search-results]");
  if (results) {
    const params = new URLSearchParams(location.search);
    const q = (params.get("q") || "").trim();
    const field = document.querySelector("#q-page");
    if (field) field.value = q;
    if (!q) return;
    const fold = (s) => (s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
    const terms = fold(q).split(/\s+/).filter(Boolean);
    fetch(results.dataset.index)
      .then((r) => r.json())
      .then((docs) => {
        const scored = docs
          .map((d) => {
            const t = fold(d.title), b = fold(d.text);
            let score = 0;
            for (const term of terms) {
              if (t.includes(term)) score += 10;
              else if (b.includes(term)) score += 1;
              else return null;
            }
            return { d, score };
          })
          .filter(Boolean)
          .sort((a, b) => b.score - a.score || (b.d.date || "").localeCompare(a.d.date || ""))
          .slice(0, 50);
        results.innerHTML = "";
        const summary = document.querySelector("[data-search-summary]");
        if (summary) summary.textContent = `${scored.length} ${summary.dataset.label || ""} «${q}»`;
        for (const { d } of scored) {
          const li = document.createElement("li");
          const a = document.createElement("a");
          a.href = d.url;
          a.textContent = d.title;
          const p = document.createElement("p");
          p.textContent = [d.type, d.date].filter(Boolean).join(" · ");
          li.append(a, p);
          results.append(li);
        }
      });
  }
})();
